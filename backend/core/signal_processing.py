"""
core/signal_processing.py — CSK Communication System Engine.

This is the centerpiece module of ChaosComm.  It implements the complete
chaotic shift keying communication chain:

    Message → Binary → Chaotic Carrier → Modulation → [Channel] → Detection → Decoded Message

Three modulation schemes:

1. CSK (Chaotic Shift Keying)
   - Bit 0 → chaotic sequence from parameter r₀
   - Bit 1 → chaotic sequence from parameter r₁
   - Receiver correlates with both templates, picks the higher
   - REQUIRES synchronization (receiver must know x₀ exactly)

2. DCSK (Differential Chaotic Shift Keying)
   - Each bit period split into two halves:
     Reference half:    r(t) = x(t)
     Information half:  i(t) = bₙ · x(t)    (bₙ ∈ {−1, +1})
   - Receiver correlates the two halves: z = Σ r[k]·i[k]
   - Decision: bₙ = sign(z)
   - NO synchronization needed — reference travels WITH the data
   - The key innovation: self-referencing eliminates the sync problem

3. FM-DCSK (Frequency-Modulated DCSK)
   - FM modulation of chaotic carrier: constant envelope
   - Better spectral properties, suitable for nonlinear amplifiers
   - Spreading factor β controls bandwidth/performance trade-off

Also included:
   - Waveform construction (pulse shaping)
   - ASCII ↔ binary encoding
   - Full pipeline: text message in → modulated waveform → detected bits → text out
   - Per-bit animation data for the frontend

LEARNER EXPLAINERS:
  CSK replaces a predictable carrier (sine wave) with an unpredictable
  one (chaotic sequence).  The transmitter and receiver share a secret:
  the map, the parameter, and the initial condition x₀.  Anyone who
  intercepts the signal sees what looks like noise — because chaos IS
  noise-like.  But the receiver, who knows the secret, can correlate
  the received signal with its own copy of the chaotic sequence and
  recover the bits.

  The catch: CSK requires the receiver to generate an EXACT replica of
  the chaotic sequence, which means perfect synchronization.  DCSK
  eliminates this by sending the reference alongside the data — at the
  cost of halving the data rate (half the bit period is "wasted" on the
  reference).  FM-DCSK adds FM modulation for a constant-envelope signal
  that plays nicer with real amplifiers.
"""

from __future__ import annotations

import math
from typing import Any

import numpy as np


